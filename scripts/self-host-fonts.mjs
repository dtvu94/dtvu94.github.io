#!/usr/bin/env node
// Copies the web fonts the site uses into src/fonts/ and writes
// src/fonts/fonts.css, so pages never depend on Google Fonts being up.
//
// The files are Google Fonts' own woff2 builds, as packaged by Fontsource
// (SIL Open Font License; each family's licence is copied next to it).
// To refresh or add a family, install the packages in a scratch folder and
// point this script at it:
//
//   mkdir /tmp/f && cd /tmp/f && npm init -y && npm i @fontsource/alex-brush …
//   node scripts/self-host-fonts.mjs /tmp/f/node_modules/@fontsource
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const source = process.argv[2];
if (!source || !existsSync(source)) {
  throw new Error('Usage: node scripts/self-host-fonts.mjs <path to node_modules/@fontsource>');
}

/** Package → weights (normal) and italic weights, as the site requests them. */
const FAMILIES = {
  inter: { normal: [400, 500, 600, 700] },
  'be-vietnam-pro': { normal: [400, 500, 600], italic: [400] },
  montserrat: { normal: [400, 500, 600] },
  lora: { normal: [400, 500], italic: [400] },
  'playfair-display': { normal: [400, 600] },
  'cormorant-garamond': { normal: [400, 500], italic: [400] },
  'dancing-script': { normal: [400, 600] },
  'great-vibes': { normal: [400] },
  'pinyon-script': { normal: [400] },
  parisienne: { normal: [400] },
  sacramento: { normal: [400] },
  'alex-brush': { normal: [400] },
  sarabun: { normal: [400, 500, 600] },
  'noto-serif-thai': { normal: [400, 500, 600] },
  charm: { normal: [400, 700] },
};
/** Scripts the invitations are written in (Vietnamese, English, Thai). */
const SUBSETS = new Set(['latin', 'latin-ext', 'vietnamese', 'thai']);

const out = path.resolve('src/fonts');
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const css = [
  '/* Self-hosted web fonts (generated by scripts/self-host-fonts.mjs — do not edit).',
  '   Google Fonts files via Fontsource, SIL Open Font License; see each folder. */',
  '',
];
let files = 0;
for (const [pkg, styles] of Object.entries(FAMILIES)) {
  const dir = path.join(source, pkg);
  const version = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8')).version;
  mkdirSync(path.join(out, pkg));
  copyFileSync(path.join(dir, 'LICENSE'), path.join(out, pkg, 'OFL.txt'));
  css.push(`/* ── ${pkg} (Fontsource ${version}) ── */`);
  for (const [style, weights] of Object.entries(styles)) {
    for (const weight of weights) {
      const sheet = readFileSync(path.join(dir, `${weight}${style === 'italic' ? '-italic' : ''}.css`), 'utf8');
      for (const block of sheet.match(/@font-face\s*{[^}]*}/g) ?? []) {
        const file = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)?.[1];
        const subset = file?.slice(pkg.length + 1).replace(/-\d+-(normal|italic)\.woff2$/, '');
        if (!file || !SUBSETS.has(subset)) {
          continue;
        }
        copyFileSync(path.join(dir, 'files', file), path.join(out, pkg, file));
        files++;
        const family = block.match(/font-family:\s*([^;]+);/)[1];
        const range = block.match(/unicode-range:\s*([^;]+);/)?.[1];
        css.push(
          '@font-face {',
          `  font-family: ${family};`,
          `  font-style: ${style};`,
          `  font-weight: ${weight};`,
          '  font-display: swap;',
          `  src: url(${pkg}/${file}) format('woff2');`,
          ...(range ? [`  unicode-range: ${range};`] : []),
          '}',
        );
      }
    }
  }
  css.push('');
}
writeFileSync(path.join(out, 'fonts.css'), css.join('\n'));
console.log(`${files} font files, ${Object.keys(FAMILIES).length} families → src/fonts/`);
